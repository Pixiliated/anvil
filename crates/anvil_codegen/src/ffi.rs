//! The interpreter's way into C. The program's C files and a generated shim are built into a
//! shared library, and every extern call goes through the shim's one entry point,
//! `anvil_ffi_call(func, args, result)`, with i64 and f64 values as their bits. The C files are
//! compiled exactly as for an executable, so a C function computes the same in both backends;
//! the shim is compiled without optimisation, so calls into the C runtime (libm's `cos`) stay
//! calls to the very functions an executable links.

use crate::link::{c_compiler, compile_c, run_compiler};
use anvil_front::ir::{FuncId, Program, Ty};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

type Entry = unsafe extern "C" fn(i64, *const u64, *mut u64);

/// A loaded library of the program's C functions; the directory it was built in goes with it.
pub struct CLibrary {
    lib: Option<libloading::Library>,
    entry: Entry,
    dir: PathBuf,
}

impl CLibrary {
    /// Calls extern function `func` (a FuncId of the program the library was built for).
    pub fn call(&self, func: FuncId, args: &[u64]) -> u64 {
        let mut result = 0u64;
        // SAFETY: the shim was generated from this program's extern signatures, and reads
        // exactly as many arguments as the function takes.
        unsafe { (self.entry)(func as i64, args.as_ptr(), &mut result) };
        result
    }
}

impl Drop for CLibrary {
    fn drop(&mut self) {
        // Unloaded first: Windows keeps a loaded library's file locked.
        drop(self.lib.take());
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

fn c_type(t: &Ty) -> &'static str {
    match t {
        Ty::Void => "void",
        Ty::I64 => "int64_t",
        Ty::F64(_) => "double",
        other => unreachable!("{other:?} crosses into C"),
    }
}

/// The shim's C source: a prototype per extern, and a switch on the FuncId.
pub fn shim(program: &Program) -> String {
    let mut prototypes: Vec<String> = Vec::new();
    let mut cases = String::new();
    for (id, f) in program.funcs.iter().enumerate() {
        let Some(x) = &f.external else { continue };
        let params: Vec<&str> = f.params.iter().map(|p| c_type(&f.locals[*p].ty)).collect();
        let list = if params.is_empty() { "void".to_string() } else { params.join(", ") };
        let proto = format!("{} {}({list});", c_type(&f.ret), x.symbol);
        if !prototypes.contains(&proto) {
            prototypes.push(proto);
        }
        let _ = writeln!(cases, "    case {id}: {{");
        let mut names = Vec::new();
        for (i, t) in params.iter().enumerate() {
            let _ = writeln!(cases, "        {t} p{i};");
            let _ = writeln!(cases, "        memcpy(&p{i}, &a[{i}], 8);");
            names.push(format!("p{i}"));
        }
        let call = format!("{}({})", x.symbol, names.join(", "));
        if f.ret == Ty::Void {
            let _ = writeln!(cases, "        {call};");
        } else {
            let _ = writeln!(cases, "        {} v = {call};", c_type(&f.ret));
            let _ = writeln!(cases, "        memcpy(r, &v, 8);");
        }
        let _ = writeln!(cases, "        return;\n    }}");
    }
    format!(
        "/* Generated by anvil: the interpreter calls the program's C functions through here. */\n\
         #include <stdint.h>\n#include <string.h>\n{}\n\
         #ifdef _WIN32\n__declspec(dllexport)\n#endif\n\
         void anvil_ffi_call(int64_t func, const uint64_t *a, uint64_t *r) {{\n    (void)a;\n    (void)r;\n    \
         switch (func) {{\n{cases}    }}\n}}\n",
        prototypes.join("\n")
    )
}

/// Builds and loads the library in a new directory under `dir`; None for a program without
/// extern functions. A C file that does not compile is an error with the compiler's message.
pub fn load(program: &Program, dir: &Path) -> Result<Option<CLibrary>, String> {
    if program.funcs.iter().all(|f| f.external.is_none()) {
        return Ok(None);
    }
    crate::link::supported()?;
    std::fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    let built = build(program, dir);
    let lib = match built {
        Ok(path) => path,
        Err(e) => {
            let _ = std::fs::remove_dir_all(dir);
            return Err(e);
        }
    };
    // SAFETY: the library is Anvil's shim and the program's C files; loading runs no Anvil
    // code, only the C files' own initialisers, as linking them into an executable would.
    let loaded =
        unsafe { libloading::Library::new(&lib) }.map_err(|e| format!("cannot load {}: {e}", lib.display()))?;
    // SAFETY: the shim defines anvil_ffi_call with exactly this signature.
    let entry: Entry = unsafe {
        *loaded.get::<Entry>(b"anvil_ffi_call\0").map_err(|e| format!("the C library has no entry point: {e}"))?
    };
    Ok(Some(CLibrary { lib: Some(loaded), entry, dir: dir.to_path_buf() }))
}

fn build(program: &Program, dir: &Path) -> Result<PathBuf, String> {
    let mut objects = compile_c(&program.c_files, dir)?;
    std::fs::write(dir.join("anvil_ffi.c"), shim(program)).map_err(|e| format!("cannot write the shim: {e}"))?;
    let (mut cmd, name) = c_compiler()?;
    cmd.current_dir(dir);
    if cfg!(windows) {
        cmd.args(["/nologo", "/Od", "/MT", "/c", "anvil_ffi.c", "/Foanvil_ffi.obj"]);
        objects.push(dir.join("anvil_ffi.obj"));
    } else {
        cmd.args(["-O0", "-fno-builtin", "-fPIC", "-c", "anvil_ffi.c", "-o", "anvil_ffi.o"]);
        objects.push(dir.join("anvil_ffi.o"));
    }
    run_compiler(&mut cmd, &name, "the C shim")?;
    let lib = dir.join(if cfg!(windows) { "anvil_ffi.dll" } else { "libanvil_ffi.so" });
    let (mut cmd, name) = c_compiler()?;
    cmd.current_dir(dir);
    if cfg!(windows) {
        cmd.args(["/nologo", "/LD", "/MT"]).args(&objects).arg(format!("/Fe{}", lib.display()));
    } else {
        cmd.arg("-shared").arg("-o").arg(&lib).args(&objects).arg("-lm");
    }
    run_compiler(&mut cmd, &name, "the C library")?;
    Ok(lib)
}
