//! The release backend: the same Cranelift IR the native backend builds, written out as C for the
//! platform's optimizing C compiler (`anvil build --release`).
//!
//! Every decision about what a program does is made once, by `Gen`, before either backend sees it:
//! this file only spells each Cranelift instruction in C, so the two cannot differ in what a
//! program means. It reads the IR before Cranelift's optimizer and inliner run and leaves that
//! work to the C compiler, which does more of it: inlining, keeping values in registers across
//! loops, and taking checks out of them.
//!
//! What C would leave open is pinned down. Integers are unsigned and wrap as Cranelift's do, signed
//! only where an instruction says so; shift amounts are masked as Cranelift masks them; division
//! and remainder never meet the cases C leaves undefined; floats are never contracted into fused
//! multiply-adds; memory is reached through casts, so the compiler is told not to assume types
//! keep their objects apart. An instruction this file does not know is an error, never a guess.

use cranelift_codegen::ir::condcodes::{FloatCC, IntCC};
use cranelift_codegen::ir::{
    types, BlockArg, BlockCall, ExternalName, Function, GlobalValueData, InstructionData, Opcode, Signature, Type, Value,
};
use cranelift_module::{DataDescription, DataId, FuncId, Init, Linkage, ModuleDeclarations, ModuleRelocTarget};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// What the release backend writes out: each function's IR and each data object, by module id.
#[derive(Default)]
pub(crate) struct CProgram {
    pub functions: Vec<(FuncId, Function)>,
    pub data: Vec<(DataId, DataDescription)>,
}

const PRELUDE: &str = r#"/* Generated by the Anvil compiler (anvil build --release). Do not edit. */
#include <stdint.h>
#include <string.h>
#include <stdlib.h>
#include <math.h>
#ifdef _MSC_VER
#include <intrin.h>
#define ANV_ALIGN(n) __declspec(align(n))
#define ANV_INLINE static __forceinline
ANV_INLINE uint8_t anv_sadd(uint64_t a, uint64_t b, uint64_t *r) { int64_t o; uint8_t f = _add_overflow_i64(0, (int64_t)a, (int64_t)b, &o); *r = (uint64_t)o; return f; }
ANV_INLINE uint8_t anv_ssub(uint64_t a, uint64_t b, uint64_t *r) { int64_t o; uint8_t f = _sub_overflow_i64(0, (int64_t)a, (int64_t)b, &o); *r = (uint64_t)o; return f; }
ANV_INLINE uint8_t anv_smul(uint64_t a, uint64_t b, uint64_t *r) { int64_t o; uint8_t f = _mul_overflow_i64((int64_t)a, (int64_t)b, &o); *r = (uint64_t)o; return f; }
ANV_INLINE uint64_t anv_clz(uint64_t x) { unsigned long i; return _BitScanReverse64(&i, x) ? 63 - i : 64; }
#else
#define ANV_ALIGN(n) __attribute__((aligned(n)))
#define ANV_INLINE static inline __attribute__((always_inline))
ANV_INLINE uint8_t anv_sadd(uint64_t a, uint64_t b, uint64_t *r) { int64_t o; uint8_t f = __builtin_add_overflow((int64_t)a, (int64_t)b, &o); *r = (uint64_t)o; return f; }
ANV_INLINE uint8_t anv_ssub(uint64_t a, uint64_t b, uint64_t *r) { int64_t o; uint8_t f = __builtin_sub_overflow((int64_t)a, (int64_t)b, &o); *r = (uint64_t)o; return f; }
ANV_INLINE uint8_t anv_smul(uint64_t a, uint64_t b, uint64_t *r) { int64_t o; uint8_t f = __builtin_mul_overflow((int64_t)a, (int64_t)b, &o); *r = (uint64_t)o; return f; }
ANV_INLINE uint64_t anv_clz(uint64_t x) { return x ? (uint64_t)__builtin_clzll(x) : 64; }
#endif
/* Cranelift's sdiv and srem of the lowest number by -1: the quotient wraps (the IR checks first),
 * the remainder is 0. C leaves both undefined. */
ANV_INLINE uint64_t anv_sdiv(uint64_t a, uint64_t b) { return (int64_t)b == -1 ? 0 - a : (uint64_t)((int64_t)a / (int64_t)b); }
ANV_INLINE uint64_t anv_srem(uint64_t a, uint64_t b) { return (int64_t)b == -1 ? 0 : (uint64_t)((int64_t)a % (int64_t)b); }
ANV_INLINE double anv_f64(uint64_t bits) { double d; memcpy(&d, &bits, 8); return d; }
ANV_INLINE uint64_t anv_bits(double d) { uint64_t b; memcpy(&b, &d, 8); return b; }
"#;

/// The C compiler's options for release code: as fast as it goes without changing a result.
#[cfg(windows)]
pub(crate) const RELEASE_FLAGS: &[&str] = &["/nologo", "/O2", "/MT", "/fp:precise", "/GS-", "/W0", "/Brepro"];
#[cfg(not(windows))]
pub(crate) const RELEASE_FLAGS: &[&str] =
    &["-O2", "-fPIC", "-w", "-fwrapv", "-fno-strict-aliasing", "-ffp-contract=off", "-fno-math-errno"];

fn c_type(t: Type) -> Result<&'static str, String> {
    Ok(match t {
        types::I8 => "uint8_t",
        types::I16 => "uint16_t",
        types::I32 => "uint32_t",
        types::I64 => "uint64_t",
        types::F32 => "float",
        types::F64 => "double",
        _ => return Err(format!("the release backend has no C type for {t}")),
    })
}

fn signed(t: Type) -> Result<&'static str, String> {
    Ok(match t {
        types::I8 => "int8_t",
        types::I16 => "int16_t",
        types::I32 => "int32_t",
        types::I64 => "int64_t",
        _ => return Err(format!("the release backend has no signed C type for {t}")),
    })
}

/// A constant of integer type `t`, as its bits.
fn int_const(t: Type, v: i64) -> Result<String, String> {
    let bits = t.bits();
    let masked = if bits >= 64 { v as u64 } else { (v as u64) & ((1u64 << bits) - 1) };
    Ok(format!("(({})0x{masked:x}ull)", c_type(t)?))
}

/// A C identifier from a symbol: the declared name with anything else replaced, and the module id
/// so two locals never share one.
fn local_name(prefix: char, id: u32, name: Option<&str>) -> String {
    let part: String = name.unwrap_or("").chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect();
    format!("{prefix}{id}_{part}")
}

struct Names<'d> {
    decls: &'d ModuleDeclarations,
}

impl Names<'_> {
    fn func(&self, id: FuncId) -> String {
        let d = self.decls.get_function_decl(id);
        match d.linkage {
            Linkage::Local => local_name('F', id.as_u32(), d.name.as_deref()),
            _ => d.name.clone().unwrap_or_default(),
        }
    }
    fn data(&self, id: DataId) -> String {
        let d = self.decls.get_data_decl(id);
        match d.linkage {
            Linkage::Local => local_name('D', id.as_u32(), d.name.as_deref()),
            _ => d.name.clone().unwrap_or_default(),
        }
    }
}

/// The C struct a function returning several values returns them in.
fn multi_name(returns: &[Type]) -> String {
    let parts: Vec<String> = returns.iter().map(|t| t.to_string()).collect();
    format!("anv_ret_{}", parts.join("_"))
}

fn ret_type(sig: &Signature) -> Result<String, String> {
    match sig.returns.len() {
        0 => Ok("void".into()),
        1 => Ok(c_type(sig.returns[0].value_type)?.into()),
        _ => Ok(format!("struct {}", multi_name(&sig.returns.iter().map(|p| p.value_type).collect::<Vec<_>>()))),
    }
}

fn param_types(sig: &Signature) -> Result<Vec<&'static str>, String> {
    sig.params.iter().map(|p| c_type(p.value_type)).collect()
}

fn prototype(name: &str, sig: &Signature, storage: &str) -> Result<String, String> {
    let params = param_types(sig)?;
    let list = if params.is_empty() {
        "void".to_string()
    } else {
        params.iter().enumerate().map(|(i, t)| format!("{t} a{i}")).collect::<Vec<_>>().join(", ")
    };
    Ok(format!("{storage}{} {name}({list})", ret_type(sig)?))
}

/// The C program: the prelude, what the runtime and C files provide, the data, then every function.
pub(crate) fn emit(decls: &ModuleDeclarations, program: &CProgram) -> Result<String, String> {
    let names = Names { decls };
    let mut out = String::from(PRELUDE);
    // Structs for functions returning several values, wherever such a signature appears.
    let mut multis = BTreeMap::new();
    let mut note = |sig: &Signature| {
        if sig.returns.len() > 1 {
            let tys: Vec<Type> = sig.returns.iter().map(|p| p.value_type).collect();
            multis.insert(multi_name(&tys), tys);
        }
    };
    for (_, d) in decls.get_functions() {
        note(&d.signature);
    }
    for (_, f) in &program.functions {
        for (_, sig) in f.dfg.signatures.iter() {
            note(sig);
        }
    }
    for (name, rets) in &multis {
        let fields: Result<Vec<String>, String> =
            rets.iter().enumerate().map(|(i, t)| Ok(format!("{} r{i};", c_type(*t)?))).collect();
        writeln!(out, "struct {name} {{ {} }};", fields?.join(" ")).unwrap();
    }
    // Every function: imports as the C they are, the program's own as static, the entry renamed so
    // a wrapper can first finish the data.
    let defined: BTreeSet<u32> = program.functions.iter().map(|(id, _)| id.as_u32()).collect();
    let mut entry = None;
    for (id, d) in decls.get_functions() {
        let name = names.func(id);
        match d.linkage {
            Linkage::Import => writeln!(out, "{};", prototype(&name, &d.signature, "extern ")?).unwrap(),
            Linkage::Export => {
                if !d.signature.params.is_empty() || !d.signature.returns.is_empty() {
                    return Err(format!("the release backend expects `{name}` to take and give nothing"));
                }
                entry = Some(name.clone());
                writeln!(out, "{};", prototype(&format!("{name}_body"), &d.signature, "static ")?).unwrap();
            }
            _ if defined.contains(&id.as_u32()) => {
                writeln!(out, "{};", prototype(&name, &d.signature, "static ")?).unwrap()
            }
            _ => {}
        }
    }
    // Data: bytes as they are, with the addresses of functions and other data written in at start.
    let mut fixups = String::new();
    for (id, desc) in &program.data {
        let name = names.data(*id);
        let bytes: Vec<u8> = match &desc.init {
            Init::Bytes { contents } => contents.to_vec(),
            Init::Zeros { size } => vec![0; *size],
            Init::Uninitialized => return Err(format!("data `{name}` was declared and never defined")),
        };
        let align = desc.align.unwrap_or(8).max(8);
        let mut list = String::new();
        for (i, b) in bytes.iter().enumerate() {
            if i % 32 == 0 {
                list.push_str("\n    ");
            }
            write!(list, "{b},").unwrap();
        }
        writeln!(out, "static ANV_ALIGN({align}) unsigned char {name}[{}] = {{{list}\n}};", bytes.len().max(1)).unwrap();
        for (offset, fr) in &desc.function_relocs {
            let target = match &desc.function_decls[*fr] {
                ModuleRelocTarget::User { namespace: 0, index } => names.func(FuncId::from_u32(*index)),
                other => return Err(format!("data `{name}` points at {other:?}, which the release backend cannot write")),
            };
            writeln!(fixups, "    {{ uint64_t a = (uint64_t)(uintptr_t)&{target}; memcpy({name} + {offset}, &a, 8); }}").unwrap();
        }
        for (offset, gv, addend) in &desc.data_relocs {
            let target = match &desc.data_decls[*gv] {
                ModuleRelocTarget::User { namespace: 1, index } => names.data(DataId::from_u32(*index)),
                other => return Err(format!("data `{name}` points at {other:?}, which the release backend cannot write")),
            };
            writeln!(
                fixups,
                "    {{ uint64_t a = (uint64_t)(uintptr_t){target} + (uint64_t)({addend}); memcpy({name} + {offset}, &a, 8); }}"
            )
            .unwrap();
        }
    }
    for (id, f) in &program.functions {
        let d = decls.get_function_decl(*id);
        let name = if d.linkage == Linkage::Export { format!("{}_body", names.func(*id)) } else { names.func(*id) };
        function(&mut out, &names, &name, f).map_err(|e| format!("{e} (in `{}`)", d.name.as_deref().unwrap_or("?")))?;
    }
    if let Some(entry) = entry {
        writeln!(out, "void {entry}(void) {{\n{fixups}    {entry}_body();\n}}").unwrap();
    }
    Ok(out)
}

struct Writer<'f, 'n, 'd> {
    f: &'f Function,
    names: &'n Names<'d>,
    out: String,
}

impl Writer<'_, '_, '_> {
    fn v(&self, v: Value) -> String {
        format!("v{}", self.f.dfg.resolve_aliases(v).as_u32())
    }
    fn ty(&self, v: Value) -> Type {
        self.f.dfg.value_type(self.f.dfg.resolve_aliases(v))
    }
    fn line(&mut self, s: String) {
        self.out.push_str("    ");
        self.out.push_str(&s);
        self.out.push('\n');
    }
    /// The function a call or address names.
    fn callee(&self, fr: cranelift_codegen::ir::FuncRef) -> Result<String, String> {
        match &self.f.dfg.ext_funcs[fr].name {
            ExternalName::User(r) => {
                let user = &self.f.params.user_named_funcs()[*r];
                if user.namespace != 0 {
                    return Err(format!("a call names namespace {}", user.namespace));
                }
                Ok(self.names.func(FuncId::from_u32(user.index)))
            }
            other => Err(format!("a call names {other:?}, which the release backend cannot write")),
        }
    }
    /// Goes to the block, its parameters first given the arguments, all read before any is set.
    fn goto(&mut self, call: &BlockCall) -> Result<String, String> {
        let pool = &self.f.dfg.value_lists;
        let block = call.block(pool);
        let params = self.f.dfg.block_params(block).to_vec();
        let mut args = Vec::new();
        for a in call.args(pool) {
            match a {
                BlockArg::Value(v) => args.push(v),
                other => return Err(format!("a branch passes {other:?}, which the release backend cannot write")),
            }
        }
        let mut s = String::from("{ ");
        for (i, (p, a)) in params.iter().zip(&args).enumerate() {
            write!(s, "{} t{i} = {}; ", c_type(self.ty(*p))?, self.v(*a)).unwrap();
        }
        for (i, p) in params.iter().enumerate() {
            write!(s, "{} = t{i}; ", self.v(*p)).unwrap();
        }
        write!(s, "goto b{}; }}", block.as_u32()).unwrap();
        Ok(s)
    }
    fn addr(&self, base: Value, offset: i32) -> String {
        format!("(uintptr_t)({} + (uint64_t)(int64_t){offset})", self.v(base))
    }
}

fn int_cc(cc: IntCC, t: Type, a: &str, b: &str) -> Result<String, String> {
    let s = signed(t)?;
    let u = c_type(t)?;
    let (cast, op) = match cc {
        IntCC::Equal => (u, "=="),
        IntCC::NotEqual => (u, "!="),
        IntCC::SignedLessThan => (s, "<"),
        IntCC::SignedLessThanOrEqual => (s, "<="),
        IntCC::SignedGreaterThan => (s, ">"),
        IntCC::SignedGreaterThanOrEqual => (s, ">="),
        IntCC::UnsignedLessThan => (u, "<"),
        IntCC::UnsignedLessThanOrEqual => (u, "<="),
        IntCC::UnsignedGreaterThan => (u, ">"),
        IntCC::UnsignedGreaterThanOrEqual => (u, ">="),
    };
    Ok(format!("(uint8_t)(({cast}){a} {op} ({cast}){b})"))
}

fn float_cc(cc: FloatCC, a: &str, b: &str) -> Result<String, String> {
    // C's comparisons are false when either side is NaN, except `!=`: as Cranelift's are.
    let e = match cc {
        FloatCC::Equal => format!("{a} == {b}"),
        FloatCC::NotEqual => format!("{a} != {b}"),
        FloatCC::LessThan => format!("{a} < {b}"),
        FloatCC::LessThanOrEqual => format!("{a} <= {b}"),
        FloatCC::GreaterThan => format!("{a} > {b}"),
        FloatCC::GreaterThanOrEqual => format!("{a} >= {b}"),
        FloatCC::Ordered => format!("{a} == {a} && {b} == {b}"),
        FloatCC::Unordered => format!("{a} != {a} || {b} != {b}"),
        FloatCC::OrderedNotEqual => format!("{a} < {b} || {a} > {b}"),
        FloatCC::UnorderedOrEqual => format!("!({a} < {b} || {a} > {b})"),
        FloatCC::UnorderedOrLessThan => format!("!({a} >= {b})"),
        FloatCC::UnorderedOrLessThanOrEqual => format!("!({a} > {b})"),
        FloatCC::UnorderedOrGreaterThan => format!("!({a} <= {b})"),
        FloatCC::UnorderedOrGreaterThanOrEqual => format!("!({a} < {b})"),
    };
    Ok(format!("(uint8_t)({e})"))
}

/// One function: its values as C locals, its blocks as labels.
fn function(out: &mut String, names: &Names, name: &str, f: &Function) -> Result<(), String> {
    let mut w = Writer { f, names, out: String::new() };
    let entry = f.layout.entry_block().ok_or("a function has no blocks")?;
    writeln!(out, "{} {{", prototype(name, &f.signature, "static ")?).unwrap();
    // Every value a block or instruction makes, declared up front.
    let mut declared = String::new();
    for block in f.layout.blocks() {
        let mut values: Vec<Value> = f.dfg.block_params(block).to_vec();
        for inst in f.layout.block_insts(block) {
            values.extend(f.dfg.inst_results(inst));
        }
        for v in values {
            writeln!(declared, "    {} v{};", c_type(f.dfg.value_type(v))?, v.as_u32()).unwrap();
        }
    }
    for (slot, data) in f.sized_stack_slots.iter() {
        let align = 1u32 << data.align_shift.max(4);
        writeln!(declared, "    ANV_ALIGN({align}) unsigned char s{}[{}];", slot.as_u32(), data.size.max(1)).unwrap();
    }
    out.push_str(&declared);
    for (i, p) in f.dfg.block_params(entry).iter().enumerate() {
        writeln!(out, "    v{} = a{i};", p.as_u32()).unwrap();
    }
    for block in f.layout.blocks() {
        w.out.push_str(&format!("b{}:;\n", block.as_u32()));
        for inst in f.layout.block_insts(block) {
            instruction(&mut w, inst)?;
        }
    }
    out.push_str(&w.out);
    out.push_str("}\n");
    Ok(())
}

fn instruction(w: &mut Writer, inst: cranelift_codegen::ir::Inst) -> Result<(), String> {
    let f = w.f;
    let data = f.dfg.insts[inst];
    let results = f.dfg.inst_results(inst).to_vec();
    let res = |i: usize| format!("v{}", results[i].as_u32());
    let rty = |i: usize| f.dfg.value_type(results[i]);
    let op = data.opcode();
    match data {
        InstructionData::UnaryImm { opcode: Opcode::Iconst, imm } => {
            let c = int_const(rty(0), imm.bits())?;
            w.line(format!("{} = {c};", res(0)));
        }
        InstructionData::UnaryIeee64 { opcode: Opcode::F64const, imm } => {
            w.line(format!("{} = anv_f64(0x{:x}ull);", res(0), imm.bits()));
        }
        InstructionData::Binary { opcode, args: [a, b] } => {
            let (x, y) = (w.v(a), w.v(b));
            let t = w.ty(a);
            let bits = t.bits();
            let e = match opcode {
                Opcode::Iadd => format!("({})({x} + {y})", c_type(t)?),
                Opcode::Isub => format!("({})({x} - {y})", c_type(t)?),
                Opcode::Imul => format!("({})({x} * {y})", c_type(t)?),
                Opcode::Band => format!("{x} & {y}"),
                Opcode::Bor => format!("{x} | {y}"),
                Opcode::Bxor => format!("{x} ^ {y}"),
                Opcode::Ishl => format!("({})({x} << ({y} & {}))", c_type(t)?, bits - 1),
                Opcode::Ushr => format!("({})({x} >> ({y} & {}))", c_type(t)?, bits - 1),
                Opcode::Sshr => format!("({})(({}){x} >> ({y} & {}))", c_type(t)?, signed(t)?, bits - 1),
                Opcode::Sdiv if t == types::I64 => format!("anv_sdiv({x}, {y})"),
                Opcode::Srem if t == types::I64 => format!("anv_srem({x}, {y})"),
                Opcode::Udiv => format!("{x} / {y}"),
                Opcode::Urem => format!("{x} % {y}"),
                Opcode::Fadd => format!("{x} + {y}"),
                Opcode::Fsub => format!("{x} - {y}"),
                Opcode::Fmul => format!("{x} * {y}"),
                Opcode::Fdiv => format!("{x} / {y}"),
                Opcode::SaddOverflow | Opcode::SsubOverflow | Opcode::SmulOverflow if t == types::I64 => {
                    let helper = match opcode {
                        Opcode::SaddOverflow => "anv_sadd",
                        Opcode::SsubOverflow => "anv_ssub",
                        _ => "anv_smul",
                    };
                    w.line(format!("{} = {helper}({x}, {y}, &{});", res(1), res(0)));
                    return Ok(());
                }
                _ => return Err(format!("the release backend cannot write `{opcode}` on {t}")),
            };
            w.line(format!("{} = {e};", res(0)));
        }
        InstructionData::IntCompare { cond, args: [a, b], .. } => {
            let e = int_cc(cond, w.ty(a), &w.v(a), &w.v(b))?;
            w.line(format!("{} = {e};", res(0)));
        }
        InstructionData::FloatCompare { cond, args: [a, b], .. } => {
            let e = float_cc(cond, &w.v(a), &w.v(b))?;
            w.line(format!("{} = {e};", res(0)));
        }
        InstructionData::Unary { opcode, arg } => {
            let x = w.v(arg);
            let t = w.ty(arg);
            let to = rty(0);
            let e = match opcode {
                Opcode::Bnot => format!("({})~{x}", c_type(t)?),
                Opcode::Ineg => format!("({})(0 - {x})", c_type(t)?),
                Opcode::Iabs => format!("({})(({}){x} < 0 ? 0 - {x} : {x})", c_type(t)?, signed(t)?),
                Opcode::Uextend | Opcode::Ireduce => format!("({}){x}", c_type(to)?),
                Opcode::Sextend => format!("({})(int64_t)({}){x}", c_type(to)?, signed(t)?),
                Opcode::Fneg => format!("-{x}"),
                Opcode::Fabs => format!("fabs({x})"),
                Opcode::Sqrt => format!("sqrt({x})"),
                Opcode::FcvtFromSint if t == types::I64 => format!("({})(int64_t){x}", c_type(to)?),
                Opcode::FcvtToSint if to == types::I64 => format!("(uint64_t)(int64_t){x}"),
                Opcode::Clz if t == types::I64 => format!("anv_clz({x})"),
                Opcode::Bitcast if t == types::I64 && to == types::F64 => format!("anv_f64({x})"),
                Opcode::Bitcast if t == types::F64 && to == types::I64 => format!("anv_bits({x})"),
                _ => return Err(format!("the release backend cannot write `{opcode}` from {t} to {to}")),
            };
            w.line(format!("{} = {e};", res(0)));
        }
        InstructionData::Load { opcode, arg, offset, .. } => {
            let a = w.addr(arg, offset.into());
            let to = rty(0);
            let e = match opcode {
                Opcode::Load => format!("*({} *){a}", c_type(to)?),
                Opcode::Uload8 => format!("({})*(uint8_t *){a}", c_type(to)?),
                Opcode::Sload8 => format!("({})(int64_t)*(int8_t *){a}", c_type(to)?),
                Opcode::Uload16 => format!("({})*(uint16_t *){a}", c_type(to)?),
                Opcode::Sload16 => format!("({})(int64_t)*(int16_t *){a}", c_type(to)?),
                Opcode::Uload32 => format!("({})*(uint32_t *){a}", c_type(to)?),
                Opcode::Sload32 => format!("({})(int64_t)*(int32_t *){a}", c_type(to)?),
                _ => return Err(format!("the release backend cannot write `{opcode}`")),
            };
            w.line(format!("{} = {e};", res(0)));
        }
        InstructionData::Store { opcode, args: [value, base], offset, .. } => {
            let a = w.addr(base, offset.into());
            let x = w.v(value);
            let s = match opcode {
                Opcode::Store => format!("*({} *){a} = {x};", c_type(w.ty(value))?),
                Opcode::Istore8 => format!("*(uint8_t *){a} = (uint8_t){x};"),
                Opcode::Istore16 => format!("*(uint16_t *){a} = (uint16_t){x};"),
                Opcode::Istore32 => format!("*(uint32_t *){a} = (uint32_t){x};"),
                _ => return Err(format!("the release backend cannot write `{opcode}`")),
            };
            w.line(s);
        }
        InstructionData::StackAddr { stack_slot, offset, .. } => {
            let off: i32 = offset.into();
            w.line(format!("{} = (uint64_t)(uintptr_t)(s{} + {off});", res(0), stack_slot.as_u32()));
        }
        InstructionData::UnaryGlobalValue { opcode: Opcode::SymbolValue, global_value } => {
            let (name, offset) = match &f.global_values[global_value] {
                GlobalValueData::Symbol { name: ExternalName::User(r), offset, .. } => {
                    let user = &f.params.user_named_funcs()[*r];
                    let off: i64 = (*offset).into();
                    match user.namespace {
                        1 => (w.names.data(DataId::from_u32(user.index)), off),
                        0 => (w.names.func(FuncId::from_u32(user.index)), off),
                        n => return Err(format!("a symbol names namespace {n}")),
                    }
                }
                other => return Err(format!("the release backend cannot write the symbol {other:?}")),
            };
            w.line(format!("{} = (uint64_t)(uintptr_t){name} + (uint64_t)({offset});", res(0)));
        }
        InstructionData::FuncAddr { func_ref, .. } => {
            let name = w.callee(func_ref)?;
            w.line(format!("{} = (uint64_t)(uintptr_t)&{name};", res(0)));
        }
        InstructionData::Call { func_ref, .. } => {
            let name = w.callee(func_ref)?;
            let args: Vec<String> = f.dfg.inst_args(inst).iter().map(|a| w.v(*a)).collect();
            let call = format!("{name}({})", args.join(", "));
            assign_results(w, &results, call)?;
        }
        InstructionData::CallIndirect { sig_ref, .. } => {
            let sig = &f.dfg.signatures[sig_ref];
            let all = f.dfg.inst_args(inst);
            let params = param_types(sig)?;
            let fptr = format!(
                "(({} (*)({}))(uintptr_t){})",
                ret_type(sig)?,
                if params.is_empty() { "void".to_string() } else { params.join(", ") },
                w.v(all[0])
            );
            let args: Vec<String> = all[1..].iter().map(|a| w.v(*a)).collect();
            assign_results(w, &results, format!("{fptr}({})", args.join(", ")))?;
        }
        InstructionData::MultiAry { opcode: Opcode::Return, .. } => {
            let args: Vec<Value> = f.dfg.inst_args(inst).to_vec();
            match args.len() {
                0 => w.line("return;".into()),
                1 => w.line(format!("return {};", w.v(args[0]))),
                _ => {
                    let tys: Vec<Type> = args.iter().map(|a| w.ty(*a)).collect();
                    let mut s = format!("{{ struct {} r; ", multi_name(&tys));
                    for (i, a) in args.iter().enumerate() {
                        write!(s, "r.r{i} = {}; ", w.v(*a)).unwrap();
                    }
                    s.push_str("return r; }");
                    w.line(s);
                }
            }
        }
        InstructionData::Jump { destination, .. } => {
            let s = w.goto(&destination)?;
            w.line(s);
        }
        InstructionData::Brif { arg, blocks: [then, otherwise], .. } => {
            let (t, e) = (w.goto(&then)?, w.goto(&otherwise)?);
            w.line(format!("if ({}) {t} else {e}", w.v(arg)));
        }
        InstructionData::Trap { .. } => w.line("abort();".into()),
        InstructionData::CondTrap { opcode, arg, .. } => {
            let test = if opcode == Opcode::Trapz { "==" } else { "!=" };
            w.line(format!("if ({} {test} 0) abort();", w.v(arg)));
        }
        InstructionData::Ternary { opcode: Opcode::Select, args: [c, a, b] } => {
            w.line(format!("{} = {} ? {} : {};", res(0), w.v(c), w.v(a), w.v(b)));
        }
        _ => return Err(format!("the release backend cannot write `{op}`")),
    }
    Ok(())
}

fn assign_results(w: &mut Writer, results: &[Value], call: String) -> Result<(), String> {
    match results.len() {
        0 => w.line(format!("{call};")),
        1 => w.line(format!("v{} = {call};", results[0].as_u32())),
        _ => {
            let tys: Vec<Type> = results.iter().map(|r| w.f.dfg.value_type(*r)).collect();
            let mut s = format!("{{ struct {} r = {call}; ", multi_name(&tys));
            for (i, r) in results.iter().enumerate() {
                write!(s, "v{} = r.r{i}; ", r.as_u32()).unwrap();
            }
            s.push('}');
            w.line(s);
        }
    }
    Ok(())
}
